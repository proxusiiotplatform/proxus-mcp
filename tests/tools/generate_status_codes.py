"""Regenerates src/Proxus.Mcp.Server/OpcUaStatusCodes.g.cs from the StatusCode list asyncua ships
(generated from the OPC Foundation's StatusCode.csv). Run with the Python that has asyncua installed:

    python generate_status_codes.py > ../../src/Proxus.Mcp.Server/OpcUaStatusCodes.g.cs
"""
from asyncua.ua.status_codes import code_to_name_doc

lines = []
for code in sorted(code_to_name_doc):
    name, doc = code_to_name_doc[code]
    if not (code & 0x80000000 or code & 0x40000000):  # Bad and Uncertain only
        continue
    doc = doc.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'        [0x{code:08X}] = ("{name}", "{doc}"),')
print("""// <auto-generated>
// Bad and Uncertain StatusCodes with their descriptions, from the OPC Foundation StatusCode list (OPC 10000-6 Annex A).
// Regenerate with tests/tools/generate_status_codes.py instead of editing by hand.
// </auto-generated>
namespace Proxus.Mcp;

public static partial class OpcUaStatusCodes
{
    private static readonly Dictionary<uint, (string Name, string Description)> Known = new()
    {""")
print("\n".join(lines))
print("""    };
}""")
